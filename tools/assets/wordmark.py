"""Fraunces outlines shaped by HarfBuzz; generation needs hb-view, verification only hashes."""
import hashlib
import math
from pathlib import Path
import re
import struct
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
FONT = "core/designsystem/src/main/res/font/fraunces_400_opsz32.ttf"
OUTPUT = "feature/launch/src/main/kotlin/net/chronoflow/feature/launch/generated/LaunchWordmark.generated.kt"
NS = {"svg": "http://www.w3.org/2000/svg"}


def guard(board):
    style = re.search(r"word: '([^']+)'", board)
    if not style or any(value not in style[1] for value in (
        "font-size: 32px", "line-height: 40px", "letter-spacing: -0.01em"
    )):
        raise ValueError("Splash wordmark differs from D8")


def font_metrics(data):
    count = struct.unpack_from(">H", data, 4)[0]
    tables = {}
    for i in range(count):
        tag, _, offset, length = struct.unpack_from(">4sIII", data, 12 + i * 16)
        tables[tag] = data[offset:offset + length]
    return (struct.unpack_from(">H", tables[b"head"], 18)[0],
            *struct.unpack_from(">hh", tables[b"hhea"], 4))


def generate(svg, metrics):
    upem, ascender, descender = metrics
    tree = ET.fromstring(svg)
    advance_units = float(tree.attrib["width"])
    scale = 32 / upem
    advance = advance_units * scale - 10 * 0.32
    baseline = (40 - ascender * scale + descender * scale) / 2 + ascender * scale
    paths = {g.attrib["id"]: g.find("svg:path", NS).attrib["d"]
             for g in tree.findall(".//svg:g[@id]", NS)}
    commands = []
    ink_x = []
    ink_y = []
    for i, use in enumerate(tree.findall(".//svg:use", NS)):
        ref = use.attrib["{http://www.w3.org/1999/xlink}href"][1:]
        dx = float(use.attrib["x"]) * scale - i * 0.32
        tokens = re.findall(r"[MLCZ]|-?\d+(?:\.\d+)?", paths[ref])
        cursor = 0
        while cursor < len(tokens):
            command = tokens[cursor]
            cursor += 1
            count = {"M": 2, "L": 2, "C": 6, "Z": 0}[command]
            coordinates = [float(v) for v in tokens[cursor:cursor + count]]
            cursor += count
            for j in range(0, count, 2):
                coordinates[j] = coordinates[j] * scale + dx
                coordinates[j + 1] = coordinates[j + 1] * scale + baseline
                ink_x.append(coordinates[j])
                ink_y.append(coordinates[j + 1])
            commands.append((command, coordinates))
    # Control bounds conservatively include cubic extrema and retain the iOS overhang rule.
    overhang = max(0, -min(ink_x), max(ink_x) - advance)
    width = math.ceil(advance + 2 * overhang)
    origin_x = (width - advance) / 2
    parts = []
    for command, coordinates in commands:
        parts.append(command)
        parts.extend(f"{v + (origin_x if i % 2 == 0 else 0):.3f}" for i, v in enumerate(coordinates))
    values = {"WIDTH_DP": width, "HEIGHT_DP": 40, "ADVANCE_DP": advance, "BASELINE_DP": baseline,
              "INK_LEFT_DP": min(ink_x) + origin_x, "INK_TOP_DP": min(ink_y),
              "INK_RIGHT_DP": max(ink_x) + origin_x, "INK_BOTTOM_DP": max(ink_y)}
    lines = ["// Generated by tools/assets/wordmark.py. Do not edit.",
             "@file:Suppress(\"ktlint:standard:max-line-length\")", "",
             "package net.chronoflow.feature.launch.generated", "", "object LaunchWordmark {"]
    lines += [f"    const val {key} = {value:.3f}f" for key, value in values.items()]
    lines += [f'    const val PATH_DATA = "{" ".join(parts)}"', "}", ""]
    return "\n".join(lines).encode()


def build(root=ROOT):
    guard((root / "_design/canvas/SplashScreen.dc.html").read_text())
    data = (root / FONT).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if not any(line.startswith(digest + "  ") and line.endswith("  " + FONT)
               for line in (root / "core/designsystem/fonts.sha256").read_text().splitlines()):
        raise ValueError("Fraunces hash differs from fonts.sha256")
    svg = subprocess.run(["/opt/homebrew/bin/hb-view", "--font-size=upem", "--margin=0",
                          "--output-format=svg", str(root / FONT), "ChronoFlow"],
                         capture_output=True, check=True).stdout
    return generate(svg, font_metrics(data))


def run(root=ROOT):
    output = root / OUTPUT
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(build(root))
    manifest = root / "tools/assets/assets.sha256"
    lines = [line for line in manifest.read_text().splitlines()
             if not line.endswith("  " + FONT) and not line.endswith("  " + OUTPUT)]
    lines += [f"{hashlib.sha256((root / path).read_bytes()).hexdigest()}  -  {path}" for path in (FONT, OUTPUT)]
    manifest.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    run()
