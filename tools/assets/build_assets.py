"""Builds the launcher icon, the notification icon and the launch moon from the design files.

`icons [--out DIR]` writes the vector drawables and the adaptive-icon XML deterministically.
`moon` rasterizes the launch moon from the iOS SVGs at the pin (needs rsvg-convert and the iOS repo).
`check` regenerates the icons into build/assets-check, compares the bytes with the committed files and
verifies the hash manifest of the moon; it never rasterizes and never reads the iOS repo.
"""

import hashlib
import importlib.util
import json
import os
import re
import subprocess
import sys
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
ICON_DIR = "_design/canvas/icon"
ANDROID_NS = "http://schemas.android.com/apk/res/android"
AAPT_NS = "http://schemas.android.com/aapt"


class AssetError(Exception):
    pass


def number(text):
    """A number as the SVG writes it, without trailing zeros (14.200 becomes 14.2)."""
    return format(Decimal(text).normalize(), "f")


def header(source):
    return f"<!-- Generated by tools/assets/build_assets.py from {source}. Do not edit. -->"


def capture(pattern, text, what):
    match = re.search(pattern, text)
    if not match:
        raise AssetError(f"{what}: pattern not found: {pattern}")
    return match.groups()


def read_svg(root, relative):
    return (root / ICON_DIR / relative).read_text()


def argb(hex_color):
    return "#FF" + hex_color.lstrip("#").upper()


def parse_background(svg, colors):
    stops = re.findall(r'<stop offset="([\d.]+)" stop-color="(#[0-9a-fA-F]{6})"/>', svg)
    expected = [colors["top"], colors["mid"], colors["hor"]]
    if [color.lower() for _, color in stops] != [c.lower() for c in expected]:
        raise AssetError(f"adaptive-background.svg stops {stops} differ from colors.json {expected}")
    if len(stops) != 3:
        raise AssetError("adaptive-background.svg must have three stops")
    return [(number(offset), color) for offset, color in stops]


def parse_moon(svg, what):
    tx, ty, scale = capture(r'<g transform="translate\(([\d.]+) ([\d.]+)\) scale\(([\d.]+)\)">', svg, what)
    (path,) = capture(r'<path d="([^"]+)"', svg, what)
    stroke, width = capture(r'stroke="(#[0-9a-fA-F]{6})" stroke-width="([\d.]+)"', svg, what)
    (cap,) = capture(r'stroke-linecap="(\w+)"', svg, what)
    (join,) = capture(r'stroke-linejoin="(\w+)"', svg, what)
    return {"tx": number(tx), "ty": number(ty), "scale": number(scale), "d": path, "stroke": stroke, "width": width, "cap": cap, "join": join}


def moon_path(moon, color, indent):
    pad = " " * indent
    return (
        f'{pad}<path\n'
        f'{pad}    android:fillColor="#00000000"\n'
        f'{pad}    android:pathData="{moon["d"]}"\n'
        f'{pad}    android:strokeColor="{argb(color)}"\n'
        f'{pad}    android:strokeLineCap="{moon["cap"]}"\n'
        f'{pad}    android:strokeLineJoin="{moon["join"]}"\n'
        f'{pad}    android:strokeWidth="{moon["width"]}" />\n'
    )


def background_xml(stops):
    items = "".join(f'                <item android:color="{argb(color)}" android:offset="{offset}" />\n' for offset, color in stops)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"{header(ICON_DIR + '/android/adaptive-background.svg')}\n"
        f'<vector xmlns:android="{ANDROID_NS}"\n'
        f'    xmlns:aapt="{AAPT_NS}"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="1024"\n    android:viewportHeight="1024">\n'
        '    <path android:pathData="M0,0h1024v1024h-1024z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient\n                android:endX="0"\n                android:endY="1024"\n'
        '                android:startX="0"\n                android:startY="0"\n                android:type="linear">\n'
        f"{items}"
        "            </gradient>\n        </aapt:attr>\n    </path>\n</vector>\n"
    )


def foreground_xml(moon, color, source):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"{header(ICON_DIR + '/android/' + source)}\n"
        f'<vector xmlns:android="{ANDROID_NS}"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="1024"\n    android:viewportHeight="1024">\n'
        f'    <group\n        android:scaleX="{moon["scale"]}"\n        android:scaleY="{moon["scale"]}"\n'
        f'        android:translateX="{moon["tx"]}"\n        android:translateY="{moon["ty"]}">\n'
        f"{moon_path(moon, color, 8)}"
        "    </group>\n</vector>\n"
    )


def stat_icon_xml(moon):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"{header(ICON_DIR + '/layers/moon-white.svg')}\n"
        f'<vector xmlns:android="{ANDROID_NS}"\n'
        '    android:width="24dp"\n    android:height="24dp"\n'
        '    android:viewportWidth="24"\n    android:viewportHeight="24">\n'
        f"{moon_path(dict(moon, width=number(moon['width'])), moon['stroke'], 4)}"
        "</vector>\n"
    )


def adaptive_xml():
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"{header(ICON_DIR + '/android')}\n"
        f'<adaptive-icon xmlns:android="{ANDROID_NS}">\n'
        '    <background android:drawable="@drawable/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )


def generate_icons(root):
    colors = json.loads((root / ICON_DIR / "colors.json").read_text())
    stops = parse_background(read_svg(root, "android/adaptive-background.svg"), colors)
    foreground = parse_moon(read_svg(root, "android/adaptive-foreground.svg"), "adaptive-foreground.svg")
    monochrome = parse_moon(read_svg(root, "android/adaptive-monochrome.svg"), "adaptive-monochrome.svg")
    if foreground["stroke"].lower() != colors["dawn"].lower():
        raise AssetError(f"adaptive-foreground.svg stroke {foreground['stroke']} differs from colors.json dawn {colors['dawn']}")
    if monochrome["stroke"].lower() != "#ffffff":
        raise AssetError(f"adaptive-monochrome.svg stroke {monochrome['stroke']} is not #ffffff")
    stat = parse_moon(read_svg(root, "layers/moon-white.svg"), "moon-white.svg")
    if stat["stroke"].lower() != "#ffffff":
        raise AssetError(f"moon-white.svg stroke {stat['stroke']} is not #ffffff")
    res = "app/src/main/res"
    return {
        f"{res}/drawable/ic_stat_moon.xml": stat_icon_xml(stat),
        f"{res}/drawable/ic_launcher_background.xml": background_xml(stops),
        f"{res}/drawable/ic_launcher_foreground.xml": foreground_xml(foreground, foreground["stroke"], "adaptive-foreground.svg"),
        f"{res}/drawable/ic_launcher_monochrome.xml": foreground_xml(monochrome, monochrome["stroke"], "adaptive-monochrome.svg"),
        f"{res}/mipmap-anydpi/ic_launcher.xml": adaptive_xml(),
        f"{res}/mipmap-anydpi/ic_launcher_round.xml": adaptive_xml(),
    }


def write_outputs(outputs, out_dir):
    for relative, text in sorted(outputs.items()):
        target = out_dir / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(text.encode("utf-8"))


def run_icons(root, out_dir):
    write_outputs(generate_icons(root), out_dir)


MOON_SOURCES = {
    "light": ("Assets/moon/launch-moon-light.svg", "5c6f92500ea5f03edb16a74a9f41eb148f34668e1ef2ef5550316dfbce6d0066"),
    "dark": ("Assets/moon/launch-moon-dark.svg", "71909bcfffbf4283bc35604acad4cd7b431ec67e900687183ec73606aa033134"),
}
MOON_SIZE = 1152
MANIFEST = "tools/assets/assets.sha256"
REPORT = "tools/tokengen/TokenGenReport.md"


def moon_outputs():
    return {
        theme: (
            f"tools/assets/moon/launch-moon-{theme}.srgb.svg",
            "app/src/main/res/drawable-xxxhdpi/launch_moon.png" if theme == "light" else "app/src/main/res/drawable-night-xxxhdpi/launch_moon.png",
        )
        for theme in MOON_SOURCES
    }


def dawn_cells(report):
    """The `dawn` row of the token report: {theme: (sRGB hex, P3 channels as written)}."""
    for line in report.splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if cells and cells[0] == "dawn" and len(cells) == 5:
            return {"light": (cells[1], cells[2]), "dark": (cells[3], cells[4])}
    raise AssetError("the token report has no dawn row")


def substitute_stroke(svg, p3, srgb_hex):
    """Replaces the one display-p3 stroke with its sRGB hex, after checking it is the dawn color."""
    found = re.findall(r'stroke="color\(display-p3 ([\d. ]+)\)"', svg)
    if len(found) != 1:
        raise AssetError(f"expected exactly one display-p3 stroke, found {len(found)}")
    if found[0] != p3:
        raise AssetError(f"stroke P3 {found[0]} differs from the dawn P3 {p3} of the token report")
    return svg.replace(f'stroke="color(display-p3 {found[0]})"', f'stroke="{srgb_hex}"')


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def read_ios(repo, pin, path):
    result = subprocess.run(["git", "-C", str(repo), "show", f"{pin}:{path}"], capture_output=True)
    if result.returncode != 0:
        raise AssetError(f"cannot read {path} at {pin} in {repo}: {result.stderr.decode().strip()}")
    return result.stdout


def run_moon(root):
    repo = Path(os.environ.get("CF_IOS_REPO", "/Users/rickgout/Sites/chronoflow-ios"))
    rsvg = os.environ.get("CF_RSVG", "/opt/homebrew/bin/rsvg-convert")
    pin = (root / "tools/ios-pin.txt").read_text().strip()
    cells = dawn_cells((root / REPORT).read_text())
    version = subprocess.run([rsvg, "--version"], capture_output=True, text=True, check=True).stdout.splitlines()[0].strip()
    lines = []
    for theme, (ios_path, expected) in MOON_SOURCES.items():
        data = read_ios(repo, pin, ios_path)
        if sha256(data) != expected:
            raise AssetError(f"{ios_path} hash {sha256(data)} differs from the expected {expected}")
        hex_color, p3 = cells[theme]
        svg_path, png_path = moon_outputs()[theme]
        svg_out = root / svg_path
        svg_out.parent.mkdir(parents=True, exist_ok=True)
        svg_out.write_bytes(substitute_stroke(data.decode("utf-8"), p3, hex_color).encode("utf-8"))
        png_out = root / png_path
        png_out.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run([rsvg, "-w", str(MOON_SIZE), "-h", str(MOON_SIZE), str(svg_out), "-o", str(png_out)], check=True)
        lines.append(f"{sha256(data)}  {ios_path}  -")
        lines.append(f"{sha256(svg_out.read_bytes())}  -  {svg_path}")
        lines.append(f"{sha256(png_out.read_bytes())}  -  {png_path}")
    manifest = root / MANIFEST
    manifest.write_text(f"# ios-pin {pin}\n# {version}\n" + "\n".join(sorted(lines, key=lambda line: line.split("  ")[2])) + "\n")


def verify_manifest(root):
    path = root / MANIFEST
    if not path.is_file():
        raise AssetError(f"missing {MANIFEST}; run `make assets`")
    spec = importlib.util.spec_from_file_location("check_sha256_manifest", ROOT / "Scripts/check-sha256-manifest.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.check(path, root)


def run_check(root):
    out_dir = root / "build/assets-check"
    outputs = generate_icons(root)
    write_outputs(outputs, out_dir)
    stale = [path for path, text in sorted(outputs.items()) if not (root / path).is_file() or (root / path).read_bytes() != text.encode("utf-8")]
    for path in stale:
        print(f"stale generated output: {path}", file=sys.stderr)
    problems = verify_manifest(root)
    for problem in problems:
        print(f"{MANIFEST}: {problem}", file=sys.stderr)
    return 1 if stale or problems else 0


def main(argv, root=ROOT):
    commands = [arg for arg in argv if arg in ("icons", "moon", "check")]
    if not commands or "check" in commands and len(commands) > 1:
        print("usage: build_assets.py [icons [--out DIR]] [moon] | check", file=sys.stderr)
        return 2
    try:
        status = 0
        for command in commands:
            if command == "icons":
                out = Path(argv[argv.index("--out") + 1]) if "--out" in argv else root
                run_icons(root, out if out.is_absolute() else root / out)
            elif command == "moon":
                run_moon(root)
            else:
                status = run_check(root)
        return status
    except (AssetError, subprocess.CalledProcessError) as error:
        print(f"build_assets: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
