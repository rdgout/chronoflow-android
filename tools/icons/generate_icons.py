"""Generates LucideGlyphs.generated.kt from the lucide-react 0.511.0 icon nodes in the boards' bundle.js.

Usage: python3 -I tools/icons/generate_icons.py [--check]
--check regenerates into build/icons/ and fails when the committed output differs.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / 'tools/icons/lucide.json'
BUNDLE = ROOT / '_design/canvas/ds/chronoflow/components/bundle.js'
OUTPUT = ROOT / 'core/designsystem/src/main/kotlin/net/chronoflow/core/designsystem/icon/LucideGlyphs.generated.kt'
CHECK_OUTPUT = ROOT / 'build/icons/LucideGlyphs.generated.kt'

HEADER = """// Generated by tools/icons/generate_icons.py from tools/icons/lucide.json and the boards' lucide-react {version} nodes. Do not edit.
package net.chronoflow.core.designsystem.icon

class LucidePath(
    val d: String,
    val filled: Boolean,
)

class LucideGlyph(
    val name: String,
    val paths: List<LucidePath>,
)

object LucideGlyphs {{
"""

ELEMENT = re.compile(r'\["(path|circle|line|rect|polyline|polygon|ellipse)",\{([^}]*)\}\]')
ATTRIBUTE = re.compile(r'([A-Za-z0-9_]+):"([^"]*)"')


def number(value):
    value = float(value)
    return str(int(value)) if value == int(value) else repr(value).rstrip('0')


def points(raw):
    nums = raw.replace(',', ' ').split()
    return [(nums[i], nums[i + 1]) for i in range(0, len(nums) - 1, 2)]


def circle(cx, cy, r):
    cx, cy, r = float(cx), float(cy), float(r)
    return f'M{number(cx - r)} {number(cy)}a{number(r)} {number(r)} 0 1 0 {number(2 * r)} 0a{number(r)} {number(r)} 0 1 0-{number(2 * r)} 0Z'


def ellipse(cx, cy, rx, ry):
    cx, cy, rx, ry = float(cx), float(cy), float(rx), float(ry)
    return f'M{number(cx - rx)} {number(cy)}a{number(rx)} {number(ry)} 0 1 0 {number(2 * rx)} 0a{number(rx)} {number(ry)} 0 1 0-{number(2 * rx)} 0Z'


def rect(a):
    x, y = float(a.get('x', 0)), float(a.get('y', 0))
    w, h = float(a['width']), float(a['height'])
    rx = float(a.get('rx', a.get('ry', 0)))
    ry = float(a.get('ry', a.get('rx', 0)))
    if rx == 0 and ry == 0:
        return f'M{number(x)} {number(y)}h{number(w)}v{number(h)}h-{number(w)}Z'
    return (
        f'M{number(x + rx)} {number(y)}h{number(w - 2 * rx)}a{number(rx)} {number(ry)} 0 0 1 {number(rx)} {number(ry)}'
        f'v{number(h - 2 * ry)}a{number(rx)} {number(ry)} 0 0 1-{number(rx)} {number(ry)}'
        f'h-{number(w - 2 * rx)}a{number(rx)} {number(ry)} 0 0 1-{number(rx)}-{number(ry)}'
        f'v-{number(h - 2 * ry)}a{number(rx)} {number(ry)} 0 0 1 {number(rx)}-{number(ry)}Z'
    )


def element_path(kind, attrs):
    if kind == 'path':
        return attrs['d']
    if kind == 'circle':
        return circle(attrs['cx'], attrs['cy'], attrs['r'])
    if kind == 'ellipse':
        return ellipse(attrs['cx'], attrs['cy'], attrs['rx'], attrs['ry'])
    if kind == 'line':
        return f"M{attrs['x1']} {attrs['y1']}L{attrs['x2']} {attrs['y2']}"
    if kind == 'rect':
        return rect(attrs)
    pts = points(attrs['points'])
    d = 'M' + ' L'.join(f'{x} {y}' for x, y in pts)
    return d + ('Z' if kind == 'polygon' else '')


def nodes(bundle, name):
    match = re.search(r'([\w$]+)=(\[\[(?:(?!\]\]).)*\]\]),[\w$]+=r\("' + re.escape(name) + r'",\1\)', bundle)
    if match is None:
        raise SystemExit(f'lucide glyph "{name}" is not in the bundle')
    result = []
    for kind, raw in ELEMENT.findall(match.group(2)):
        attrs = dict(ATTRIBUTE.findall(raw))
        result.append((element_path(kind, attrs), attrs.get('fill') == 'currentColor'))
    return result


def pascal(name):
    return ''.join(part.capitalize() for part in name.split('-'))


def render(manifest, bundle):
    out = [HEADER.format(version=manifest['version'])]
    for name in sorted(manifest['glyphs']):
        paths = ',\n'.join(
            f'                LucidePath("{d}", {"true" if filled else "false"})' for d, filled in nodes(bundle, name)
        )
        out.append(f'    val {pascal(name)} =\n        LucideGlyph(\n            "{name}",\n            listOf(\n{paths},\n            ),\n        )\n')
    out.append('}\n')
    return '\n'.join(out[:1]) + '\n'.join(out[1:-1]) + out[-1]


def generate():
    manifest = json.loads(MANIFEST.read_text())
    return render(manifest, BUNDLE.read_text())


def main(argv):
    text = generate()
    if '--check' in argv:
        CHECK_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        CHECK_OUTPUT.write_text(text)
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f'{OUTPUT.relative_to(ROOT)} is out of date; run make vectors', file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
