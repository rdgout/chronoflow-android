"""Generates LucideGlyphs.generated.kt from the lucide-react 0.511.0 icon nodes in the boards' bundle.js.

Usage: python3 -I tools/icons/generate_icons.py [--check]
--check regenerates into build/icons/ and fails when the committed output differs.
"""
import json
import re
import sys
import hashlib
import xml.etree.ElementTree as ET
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / 'tools/icons/lucide.json'
BUNDLE = ROOT / '_design/canvas/ds/chronoflow/components/bundle.js'
OUTPUT = ROOT / 'core/designsystem/src/main/kotlin/net/chronoflow/core/designsystem/icon/LucideGlyphs.generated.kt'
CHECK_OUTPUT = ROOT / 'build/icons/LucideGlyphs.generated.kt'

HEADER = """// Generated by tools/icons/generate_icons.py from tools/icons/lucide.json and the boards' lucide-react {version} nodes. Do not edit.
package net.chronoflow.core.designsystem.icon

class LucidePath(
    val d: String,
    val filled: Boolean,
)

class LucideGlyph(
    val name: String,
    val paths: List<LucidePath>,
)

object LucideGlyphs {{
"""

ELEMENT = re.compile(r'\["(path|circle|line|rect|polyline|polygon|ellipse)",\{([^}]*)\}\]')
ATTRIBUTE = re.compile(r'([A-Za-z0-9_]+):"([^"]*)"')


def number(value):
    value = float(value)
    return str(int(value)) if value == int(value) else repr(value).rstrip('0')


def points(raw):
    nums = raw.replace(',', ' ').split()
    return [(nums[i], nums[i + 1]) for i in range(0, len(nums) - 1, 2)]


def circle(cx, cy, r):
    cx, cy, r = float(cx), float(cy), float(r)
    return f'M{number(cx - r)} {number(cy)}a{number(r)} {number(r)} 0 1 0 {number(2 * r)} 0a{number(r)} {number(r)} 0 1 0-{number(2 * r)} 0Z'


def ellipse(cx, cy, rx, ry):
    cx, cy, rx, ry = float(cx), float(cy), float(rx), float(ry)
    return f'M{number(cx - rx)} {number(cy)}a{number(rx)} {number(ry)} 0 1 0 {number(2 * rx)} 0a{number(rx)} {number(ry)} 0 1 0-{number(2 * rx)} 0Z'


def rect(a):
    x, y = float(a.get('x', 0)), float(a.get('y', 0))
    w, h = float(a['width']), float(a['height'])
    rx = float(a.get('rx', a.get('ry', 0)))
    ry = float(a.get('ry', a.get('rx', 0)))
    if rx == 0 and ry == 0:
        return f'M{number(x)} {number(y)}h{number(w)}v{number(h)}h-{number(w)}Z'
    return (
        f'M{number(x + rx)} {number(y)}h{number(w - 2 * rx)}a{number(rx)} {number(ry)} 0 0 1 {number(rx)} {number(ry)}'
        f'v{number(h - 2 * ry)}a{number(rx)} {number(ry)} 0 0 1-{number(rx)} {number(ry)}'
        f'h-{number(w - 2 * rx)}a{number(rx)} {number(ry)} 0 0 1-{number(rx)}-{number(ry)}'
        f'v-{number(h - 2 * ry)}a{number(rx)} {number(ry)} 0 0 1 {number(rx)}-{number(ry)}Z'
    )


def element_path(kind, attrs):
    if kind == 'path':
        return attrs['d']
    if kind == 'circle':
        return circle(attrs['cx'], attrs['cy'], attrs['r'])
    if kind == 'ellipse':
        return ellipse(attrs['cx'], attrs['cy'], attrs['rx'], attrs['ry'])
    if kind == 'line':
        return f"M{attrs['x1']} {attrs['y1']}L{attrs['x2']} {attrs['y2']}"
    if kind == 'rect':
        return rect(attrs)
    pts = points(attrs['points'])
    d = 'M' + ' L'.join(f'{x} {y}' for x, y in pts)
    return d + ('Z' if kind == 'polygon' else '')


def nodes(bundle, name):
    match = re.search(r'([\w$]+)=(\[\[(?:(?!\]\]).)*\]\]),[\w$]+=r\("' + re.escape(name) + r'",\1\)', bundle)
    if match is None:
        raise SystemExit(f'lucide glyph "{name}" is not in the bundle')
    result = []
    for kind, raw in ELEMENT.findall(match.group(2)):
        attrs = dict(ATTRIBUTE.findall(raw))
        result.append((element_path(kind, attrs), attrs.get('fill') == 'currentColor'))
    return result


def pascal(name):
    return ''.join(part.capitalize() for part in name.split('-'))



class BoardIcons(HTMLParser):
    def __init__(self):
        super().__init__()
        self.current = None
        self.icons = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'svg':
            self.current = [] if attrs.get('viewbox') == '0 0 24 24' else None
        elif self.current is not None and tag in ('path', 'circle', 'line', 'rect', 'polyline', 'polygon', 'ellipse'):
            self.current.append((tag, attrs))

    def handle_endtag(self, tag):
        if tag == 'svg' and self.current is not None:
            self.icons.append(self.current)
            self.current = None


def board_nodes(name, entry, root=ROOT):
    parser = BoardIcons()
    parser.feed((root / '_design/canvas' / (entry['board'] + '.dc.html')).read_text())
    first = entry['first']
    expected_attrs = None
    if first.startswith('<'):
        expected_attrs = dict(re.findall(r'([\w-]+)="([^"]*)"', first))
    for icon in parser.icons:
        if not icon:
            continue
        kind, attrs = icon[0]
        if (expected_attrs is not None and kind == first[1:].split()[0] and all(attrs.get(k) == v for k, v in expected_attrs.items())) or attrs.get('d') == first:
            return [(element_path(k, a), a.get('fill') == 'currentColor') for k, a in icon]
    raise SystemExit(f'lucide glyph "{name}" has no matching SVG in board {entry["board"]}')

def render(manifest, bundle):
    out = [HEADER.format(version=manifest['version'])]
    for name in sorted(manifest['glyphs']):
        paths = ',\n'.join(
            f'                LucidePath("{d}", {"true" if filled else "false"})' for d, filled in (board_nodes(name, manifest["glyphs"][name]) if manifest["glyphs"][name]["source"] == "board" else nodes(bundle, name))
        )
        out.append(f'    val {pascal(name)} =\n        LucideGlyph(\n            "{name}",\n            listOf(\n{paths},\n            ),\n        )\n')
    out.append('}\n')
    return '\n'.join(out[:1]) + '\n'.join(out[1:-1]) + out[-1]


def generate():
    manifest = json.loads(MANIFEST.read_text())
    return render(manifest, BUNDLE.read_text())



def material_render():
    base = ROOT / 'tools/icons/material-symbols'
    for line in (base / 'MANIFEST.sha256').read_text().splitlines():
        digest, name = line.split('  ', 1)
        if hashlib.sha256((base / name).read_bytes()).hexdigest() != digest:
            raise SystemExit(f'Material Symbols checksum mismatch: {name}')
    out = ['// Generated by tools/icons/generate_icons.py from Material Symbols Rounded 0.48.2. Do not edit.\n'
           'package net.chronoflow.core.designsystem.icon\n\n'
           'import androidx.compose.ui.graphics.Color\n'
           'import androidx.compose.ui.graphics.SolidColor\n'
           'import androidx.compose.ui.graphics.vector.ImageVector\n'
           'import androidx.compose.ui.graphics.vector.addPathNodes\n'
           'import androidx.compose.ui.unit.dp\n\nobject MaterialSymbols {\n']
    for path in sorted((base / 'rounded').glob('*.svg')):
        svg = ET.fromstring(path.read_text())
        box = svg.attrib.get('viewBox')
        if box != '0 -960 960 960':
            raise SystemExit(f'unexpected viewBox in {path}: {box}')
        name = ''.join(p.capitalize() for p in path.stem.replace('-', '_').split('_'))
        out.append(f'    val {name}: ImageVector by lazy {{\n        ImageVector.Builder("{name}", 24.dp, 24.dp, 960f, 960f, autoMirror = {str(path.stem == "arrow_back").lower()})\n            .apply {{\n                addGroup(translationY = 960f)\n')
        for node in svg:
            if node.tag.split('}')[-1] != 'path':
                raise SystemExit(f'unsupported Material Symbols element {node.tag}')
            out.append(f'                addPath(addPathNodes("{node.attrib["d"]}"), fill = SolidColor(Color.Black))\n')
        out.append('                clearGroup()\n            }.build()\n    }\n')
    return ''.join(out) + '}\n'

def main(argv):
    outputs = [(OUTPUT, generate()), (OUTPUT.with_name('MaterialSymbols.generated.kt'), material_render())]
    stale = False
    for path, text in outputs:
        if '--check' in argv:
            check_path = CHECK_OUTPUT.with_name(path.name)
            check_path.parent.mkdir(parents=True, exist_ok=True)
            check_path.write_text(text)
            if not path.exists() or path.read_text() != text:
                print(f'{path.relative_to(ROOT)} is out of date; run make vectors', file=sys.stderr)
                stale = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    return int(stale)


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
