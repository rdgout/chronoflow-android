package net.chronoflow.tools.tokengen

/** One appearance of a token: clipped sRGB bytes, alpha, and the Display P3 channels (reference only). */
class Swatch(
    val rgb: RGB,
    val alpha: Double,
    val p3: List<Double>?,
) {
    val argb: Long
        get() {
            val bytes = rgb.values.map { roundHalfUp(it * 255) }
            return (roundHalfUp(alpha * 255) shl 24) or (bytes[0] shl 16) or (bytes[1] shl 8) or bytes[2]
        }

    val argbLiteral: String get() = "0x" + String.format(java.util.Locale.ROOT, "%08X", argb)
}

class ColorRow(
    val name: String,
    val light: Swatch,
    val dark: Swatch,
) {
    val camel: String get() = camelCase(name)
}

fun colorRows(source: DesignSource): List<ColorRow> {
    val all =
        DesignSource.names + DesignSource.authDerivedNames + DesignSource.wizardDerivedNames +
            DesignSource.androidDerivedNames
    return all.map { name ->
        fun swatch(appearance: String): Swatch {
            if (name == "wizard-picker-fill") {
                val pill = source.wizardPickerFill()
                return Swatch(RGB(pill.take(3).map { it / 255 }), pill[3], null)
            }
            val lab = source.color(name, appearance)
            val androidOnly = name in DesignSource.androidDerivedNames
            return Swatch(lab.rgb(p3 = false), lab.alpha, if (androidOnly) null else lab.rgb(p3 = true).values)
        }
        ColorRow(name, swatch("light"), swatch("dark"))
    }
}

fun renderReport(
    rows: List<ColorRow>,
    source: DesignSource,
): String {
    val report = StringBuilder()
    report.append("# TokenGen report\n\n")
    report.append(
        "Source: `_design/canvas/ds/chronoflow/tokens.json`. " +
            "OKLCH → OKLab → linear sRGB → clip → sRGB transfer curve; " +
            "the P3 columns are linear Display P3 → clip → the same transfer curve, " +
            "for reference only (OQ-A7). " +
            "Conversion matrices follow [CSS Color 4](https://www.w3.org/TR/css-color-4/#color-conversion-code). " +
            "Hex values are clipped sRGB.\n\n",
    )
    report.append("| Token | Light sRGB | Light P3 | Dark sRGB | Dark P3 |\n|---|---|---|---|---|\n")
    for (row in rows) {
        report.append("| ${row.camel} |")
        for (swatch in listOf(row.light, row.dark)) {
            val alpha = if (swatch.alpha < 1) " α${swatch.alpha}" else ""
            val p3 = swatch.p3?.joinToString(" ") { number(it) } ?: "—"
            report.append(" ${swatch.rgb.hex}$alpha | $p3 |")
        }
        report.append("\n")
    }
    for (appearance in listOf("light", "dark")) {
        val stops = source.ramp(appearance).size
        report.append(
            "\n${appearance.replaceFirstChar {
                it.uppercase()
            }} sky: $stops stops, including exact mid ${source.midStop(
                appearance,
            )}; " +
                "encoded sRGB channel interpolation checked at 1001 points to ±0.25/255.\n",
        )
    }
    report.append(
        "\n## Type notes\n\n`screenDayTitle` stays 18/28 as iOS generates it from tokens.json; " +
            "the day header uses `planDayTitle` 18/26 (OQ-A9).\n",
    )
    return report.toString()
}

private const val INPUTS = "_design/canvas/ds/chronoflow/tokens.json, theme.css and the boards"

fun renderCfColors(rows: List<ColorRow>): String {
    val out = StringBuilder()
    out.append("// Generated by :tools:tokengen from $INPUTS. Do not edit.\n")
    out.append("package net.chronoflow.core.designsystem.generated\n\n")
    out.append("import androidx.compose.runtime.Immutable\nimport androidx.compose.ui.graphics.Color\n\n")
    out.append("@Immutable\nclass CfColors(\n    val isDark: Boolean,\n")
    for (row in rows) out.append("    val ${row.camel}: Color,\n")
    out.append(")\n")
    for ((label, dark) in listOf("CfLightColors" to false, "CfDarkColors" to true)) {
        out.append("\nval $label =\n    CfColors(\n        isDark = $dark,\n")
        for (row in rows) {
            out.append(
                "        ${row.camel} = Color(${(if (dark) row.dark else row.light).argbLiteral}),\n",
            )
        }
        out.append("    )\n")
    }
    return out.toString()
}

fun renderTimelinePalette(rows: List<ColorRow>): String {
    val out = StringBuilder()
    out.append("// Generated by :tools:tokengen from $INPUTS. Do not edit.\n")
    out.append("package net.chronoflow.core.plan.generated\n\n")
    out.append("class TimelinePalette(\n")
    for (row in rows) out.append("    val ${row.camel}: Int,\n")
    out.append(") {\n    companion object {\n")
    for ((label, dark) in listOf("Light" to false, "Dark" to true)) {
        out.append("        val $label =\n            TimelinePalette(\n")
        for (row in rows) {
            out.append(
                "                ${row.camel} = ${(if (dark) row.dark else row.light).argbLiteral}.toInt(),\n",
            )
        }
        out.append("            )\n")
    }
    out.append("    }\n}\n")
    return out.toString()
}

fun renderLaunchColors(swatch: Swatch): String {
    val argb = "#" + String.format(java.util.Locale.ROOT, "%08X", swatch.argb)
    return """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by :tools:tokengen from $INPUTS (sky-top). Do not edit. -->
<resources>
    <color name="launch_sky_top">$argb</color>
</resources>
"""
}
