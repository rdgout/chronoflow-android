package net.chronoflow.tools.tokengen

private const val DIMENS_INPUTS = "tokens.json, the boards, the bundled components and tools/tokengen/ios/*.source.json"

private val FACE_ORDER =
    listOf(
        "Figtree400",
        "Figtree500",
        "Figtree600",
        "Figtree700",
        "Fraunces400Opsz20",
        "Fraunces400Opsz32",
        "Fraunces400Opsz48",
        "Fraunces500Opsz20",
        "Fraunces500Opsz32",
        "Fraunces500Opsz48",
        "System400",
    )

private fun faceLiteral(face: String) = "CfFace.$face"

private fun nullable(value: Double?) = value?.let { floatLiteral(it) } ?: "null"

private fun em(entry: TypeEntry) = floatLiteral(entry.trackingPt / entry.size)

fun renderDimens(
    planUI: TokenSet,
    auth: TokenSet,
    settings: TokenSet,
    terms: TokenSet,
    welcome: TokenSet,
): String {
    val out = StringBuilder()
    out.append("// Generated by :tools:tokengen from $DIMENS_INPUTS. Do not edit.\n")
    out.append("package net.chronoflow.core.designsystem.generated\n")
    for ((name, set) in listOf(
        "PlanUITokens" to planUI,
        "AuthTokens" to auth,
        "SettingsTokens" to settings,
        "TermsTokens" to terms,
        "WelcomeTokens" to welcome,
    )) {
        out.append("\nobject $name {\n")
        for (metric in set.metrics) out.append("    const val ${metric.name}: Float = ${floatLiteral(metric.value)}\n")
        for ((listName, values) in set.lists) {
            out.append("    val $listName: List<Float> = listOf(${values.joinToString(", ") { floatLiteral(it) }})\n")
        }
        out.append("}\n")
    }
    return out.toString()
}

fun renderTypeScale(
    plan: PlanTokens,
    fonts: List<TypeEntry>,
    planUI: TokenSet,
    auth: TokenSet,
    settings: TokenSet,
    terms: TokenSet,
): String {
    val out = StringBuilder()
    out.append("// Generated by :tools:tokengen from $DIMENS_INPUTS. Do not edit.\n")
    out.append("package net.chronoflow.core.designsystem.generated\n\n")
    out.append("enum class CfFace {\n")
    for (face in FACE_ORDER) out.append("    $face,\n")
    out.append("}\n\n")
    out.append(
        "class CfTypeMetrics(\n    val size: Float,\n    val lineHeight: Float?,\n    val letterSpacingEm: Float,\n)\n\n",
    )
    out.append(
        "class CfTypeSpec(\n    val face: CfFace,\n    val size: Float,\n    val lineHeight: Float?,\n    val letterSpacingEm: Float,\n    val allowFontSynthesis: Boolean = true,\n)\n\n",
    )
    out.append("object TypeMetrics {\n")
    for (entry in fonts) {
        out.append(
            "    val ${entry.name} = CfTypeMetrics(${floatLiteral(
                entry.size,
            )}, ${nullable(entry.lineHeight)}, ${em(entry)})\n",
        )
    }
    out.append("}\n\nobject PlanTypeMetrics {\n")
    for (entry in plan.types) {
        out.append(
            "    val ${entry.name} = CfTypeMetrics(${floatLiteral(entry.size)}, ${nullable(entry.lineHeight)}, 0f)\n",
        )
        out.append("    val ${entry.name}Face = ${faceLiteral(entry.face)}\n")
    }
    out.append("}\n\nobject CfTypeScale {\n")
    for (entry in planUI.styles + auth.styles + settings.styles + terms.styles) {
        val synthesis = if (entry.allowFontSynthesis) "" else ", allowFontSynthesis = false"
        out.append(
            "    val ${entry.name} = CfTypeSpec(${faceLiteral(entry.face)}, ${floatLiteral(entry.size)}, " +
                "${nullable(entry.lineHeight)}, ${em(entry)}$synthesis)\n",
        )
    }
    out.append("}\n")
    return out.toString()
}

fun renderPlanMetrics(plan: PlanTokens): String {
    val out = StringBuilder()
    out.append(
        "// Generated by :tools:tokengen from tools/tokengen/ios/Plan.source.json and tokens.json. Do not edit.\n",
    )
    out.append("package net.chronoflow.core.plan.generated\n\nobject PlanMetrics {\n")
    for (metric in plan.metrics) out.append("    const val ${metric.name}: Double = ${doubleLiteral(metric.value)}\n")
    out.append("    const val pointsPerMinute: Double = pointsPerHour / 60\n")
    for (entry in plan.overlay) {
        out.append("    // Android overlay: replaces ${entry.replaces}\n")
        out.append("    const val ${entry.name}: Double = ${doubleLiteral(entry.value)}\n")
    }
    out.append("}\n")
    return out.toString()
}
