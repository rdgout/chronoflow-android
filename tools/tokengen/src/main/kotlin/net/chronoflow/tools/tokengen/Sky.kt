package net.chronoflow.tools.tokengen

import kotlin.math.PI
import kotlin.math.exp
import kotlin.math.sqrt

class Press(
    val scale: Double,
    val opacity: Double,
    val durationMillis: Int,
)

/** Port of the `cf-press` guard of iOS `Generator.swift`; a function of the `theme.css` text. */
fun pressTokens(theme: String): Press {
    val scale = firstCapture("""scale\(([\d.]+)\)""", theme)
    val opacity = firstCapture("""opacity: ([\d.]+); \}""", theme)
    val duration = firstCapture("""transition: transform ([\d.]+)ms ease""", theme)
    if (scale != "0.97" || opacity != "0.85" || duration != "120" ||
        !theme.contains(".cf-press { transition: none; }") ||
        !theme.contains(".cf-press:active { transform: none; }")
    ) {
        throw GenerationError("cf-press differs from plan")
    }
    return Press(scale.toDouble(), opacity.toDouble(), duration.toInt())
}

class LaunchPaintModel(
    val haloStops: List<Pair<Double, Double>>,
    val planeAlphas: List<Double>,
)

/** Port of the splash-plane guard and the halo and plane tables of iOS `Generator.swift`. */
fun launchPaint(splash: String): LaunchPaintModel {
    if (!splash.contains("background: #fff;") ||
        !splash.contains("box-shadow: 0 0 80px 20px") ||
        !splash.contains("box-shadow: 0 0 10px 2px rgba(255,255,255,0.8)")
    ) {
        throw GenerationError("splash plane white differs from plan")
    }
    val halo =
        listOf(0.0 to 0.0, (90.0 / 250) to 0.0) +
            (0..79).map { k ->
                val r = 90.01 + 2.0 * k
                (r / 250) to blurredDisc(r, 110.0, 40.0) * 0.45
            } + listOf(1.0 to 0.0)
    val plane = (0..48).map { k -> blurredDisc(0.5 * k, 6.0, 5.0) * 0.8 }
    return LaunchPaintModel(halo, plane)
}

private fun blurredDisc(
    radius: Double,
    disc: Double,
    sigma: Double,
): Double {
    val step = disc / 256
    var result = 0.0
    for (index in 0 until 256) {
        val y = (index + 0.5) * step
        val edge = sqrt(disc * disc - y * y)
        val horizontal = (erf((edge - radius) / (sqrt(2.0) * sigma)) - erf((-edge - radius) / (sqrt(2.0) * sigma))) / 2
        result += horizontal * exp(-y * y / (2 * sigma * sigma)) / (sqrt(2 * PI) * sigma) * step * 2
    }
    return result
}

private const val INPUTS = "_design/canvas/theme.css, SplashScreen.dc.html and tokens.json"

fun renderSky(
    source: DesignSource,
    press: Press,
    paint: LaunchPaintModel,
): String {
    val out = StringBuilder()
    out.append("// Generated by :tools:tokengen from $INPUTS. Do not edit.\n")
    out.append("package net.chronoflow.core.designsystem.generated\n\n")
    out.append("import androidx.compose.runtime.Immutable\nimport androidx.compose.ui.graphics.Color\n\n")
    out.append("@Immutable\nclass SkyStop(\n    val location: Float,\n    val color: Color,\n)\n\n")
    out.append("object SkyRamp {\n")
    for (appearance in listOf("light", "dark")) {
        out.append("    val $appearance: List<SkyStop> =\n        listOf(\n")
        for (stop in source.ramp(appearance)) {
            val swatch = Swatch(stop.color, 1.0, null)
            out.append("            SkyStop(${floatLiteral(stop.location)}, Color(${swatch.argbLiteral})),\n")
        }
        out.append("        )\n")
        if (appearance == "light") out.append("\n")
    }
    out.append("}\n\n")
    out.append(
        "object PressTokens {\n    const val scale = ${floatLiteral(
            press.scale,
        )}\n    const val opacity = ${floatLiteral(press.opacity)}\n" +
            "    const val durationMillis = ${press.durationMillis}\n    val curve = floatArrayOf(0.25f, 0.1f, 0.25f, 1f)\n}\n\n",
    )
    out.append("object LaunchPaint {\n    val white = Color(0xFFFFFFFF)\n\n")
    out.append("    val haloPositions =\n        floatArrayOf(\n")
    for (stop in paint.haloStops) out.append("            ${floatLiteral(stop.first)},\n")
    out.append("        )\n\n    val haloAlphas =\n        floatArrayOf(\n")
    for (stop in paint.haloStops) out.append("            ${floatLiteral(stop.second)},\n")
    out.append("        )\n\n    val planeAlphas =\n        floatArrayOf(\n")
    for (alpha in paint.planeAlphas) out.append("            ${floatLiteral(alpha)},\n")
    out.append("        )\n}\n")
    return out.toString()
}
