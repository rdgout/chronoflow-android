plugins {
    id("chronoflow.jvm.library")
}

dependencies {
    implementation(libs.kotlinx.serialization.json)
}

val repoRoot = rootProject.layout.projectDirectory
val designInputs =
    repoRoot.asFileTree.matching {
        include("_design/canvas/*.dc.html", "_design/canvas/theme.css", "_design/canvas/ds/chronoflow/**")
    }
val iosInputs = layout.projectDirectory.dir("ios")
val committedOutputs =
    listOf(
        "core/designsystem/src/main/kotlin/net/chronoflow/core/designsystem/generated",
        "core/plan/src/main/kotlin/net/chronoflow/core/plan/generated",
        "app/src/main/res/values/colors_launch.xml",
        "app/src/main/res/values-night/colors_launch.xml",
        "tools/tokengen/TokenGenReport.md",
    ).map { repoRoot.asFileTree.matching { include("$it/**", it) } }

tasks.register<JavaExec>("generateTokens") {
    group = "chronoflow"
    description = "Regenerates every token output into the repository."
    classpath = sourceSets["main"].runtimeClasspath
    mainClass.set("net.chronoflow.tools.tokengen.MainKt")
    args("--root", repoRoot.asFile.absolutePath)
    inputs.files(designInputs)
    inputs.dir(iosInputs)
    inputs.file(repoRoot.file("tools/tokengen/android-overlay.json"))
    outputs.upToDateWhen { false }
}

tasks.register<JavaExec>("verifyTokens") {
    group = "verification"
    description = "Fails when a committed token output differs from the regenerated bytes."
    val stamp = layout.buildDirectory.file("verify-tokens.stamp")
    classpath = sourceSets["main"].runtimeClasspath
    mainClass.set("net.chronoflow.tools.tokengen.MainKt")
    args("--root", repoRoot.asFile.absolutePath, "--check", "--stamp", stamp.get().asFile.absolutePath)
    inputs.files(designInputs)
    inputs.dir(iosInputs)
    inputs.file(repoRoot.file("tools/tokengen/android-overlay.json"))
    committedOutputs.forEach { inputs.files(it) }
    outputs.file(stamp)
}

tasks.withType<Test>().configureEach {
    systemProperty("cf.repoRoot", repoRoot.asFile.absolutePath)
    inputs.files(designInputs)
    inputs.dir(iosInputs)
    inputs.file(repoRoot.file("tools/tokengen/android-overlay.json"))
}
