"""Regenerate the verification appendix from every recorded plan question/default."""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]


def questions(plan):
    rows = []
    seen = set()
    for line in plan.splitlines():
        if not re.match(r'^\| OQ-[^ ]+ \|', line):
            continue
        fields = line.strip('| ').split(' | ')
        if len(fields) not in (3, 4):
            raise ValueError('unrecognized question row')
        identifier, _, default = fields[:3]
        if identifier in seen:
            raise ValueError('duplicate question: ' + identifier)
        seen.add(identifier)
        if identifier == 'OQ-A68':
            raise ValueError('OQ-A68 is intentionally unused')
        if len(fields) == 4:
            phases = fields[3]
        else:
            match = re.search(r'\bAffects (.+?)\.$', default)
            if not match:
                raise ValueError('question has no affected phases: ' + identifier)
            phases = match[1]
        if not default.strip() or not phases.strip():
            raise ValueError('empty default or affected phases: ' + identifier)
        rows.append((identifier, default, phases))
    if not rows:
        raise ValueError('no question evidence')
    return rows


def render(plan):
    rows = questions(plan)
    header = ('# Verification question register\n\n'
              'Generated by `python3 -I Scripts/verification-questions.py` from [plan.md](../plan.md).\n'
              'Every recorded default is reproduced verbatim; historical resolved rows are not reopened.\n'
              'Phase 14 evidence/resolutions are in [verification.md](verification.md#6-open-questions-on-their-defaults).\n\n'
              f'{len(rows)} question rows, including legacy phase identifiers. OQ-A68 remains intentionally unused.\n\n'
              '')
    return (header + ''.join(f'- **{identifier}** — {default} — Affected phases: {phases}.\n\n'
                             for identifier, default, phases in rows)).rstrip() + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'docs/verification-questions.md'
    content = render((ROOT / 'plan.md').read_text())
    if args.check:
        if not output.is_file() or output.read_text() != content:
            print('verification-questions: stale register', file=sys.stderr)
            return 1
    else:
        output.write_text(content)
    print('verification-questions:', len(questions((ROOT / 'plan.md').read_text())), 'rows')
    return 0


if __name__ == '__main__':
    sys.exit(main())
