        darkColorScheme(
            primary = dawnText,
            onPrimary = if (isDark) dawnForeground else primaryForeground,
            primaryContainer = systemSelected,
            onPrimaryContainer = dawnText,
            secondary = dawnText,
            onSecondary = if (isDark) dawnForeground else primaryForeground,
            secondaryContainer = systemSelected,
            onSecondaryContainer = dawnText,
            tertiary = dawn,
            onTertiary = dawnForeground,
            tertiaryContainer = systemSelected,
            onTertiaryContainer = dawnText,
            background = background,
            onBackground = foreground,
            surface = background,
            onSurface = foreground,
            surfaceVariant = muted,
            onSurfaceVariant = mutedForeground,
            surfaceTint = Color.Transparent,
            inverseSurface = foreground,
            inverseOnSurface = background,
            inversePrimary = dawn,
            error = destructive,
            onError = destructiveForeground,
            errorContainer = authErrorBackground,
            onErrorContainer = cardForeground,
            outline = mutedForeground,
            outlineVariant = border,
            scrim = Color.Black,
            surfaceBright = popover,
            surfaceDim = surface2,
            surfaceContainer = popover,
            surfaceContainerHigh = popover,
            surfaceContainerHighest = muted,
            surfaceContainerLow = card,
            surfaceContainerLowest = card,
            primaryFixed = systemSelected,
            primaryFixedDim = systemSelected,
            onPrimaryFixed = dawnText,
            onPrimaryFixedVariant = dawnText,
            secondaryFixed = systemSelected,
            secondaryFixedDim = systemSelected,
            onSecondaryFixed = dawnText,
            onSecondaryFixedVariant = dawnText,
            tertiaryFixed = systemSelected,
            tertiaryFixedDim = systemSelected,
            onTertiaryFixed = dawnText,
            onTertiaryFixedVariant = dawnText,
        )
    } else {
        lightColorScheme(
            primary = dawnText,
            onPrimary = if (isDark) dawnForeground else primaryForeground,
            primaryContainer = systemSelected,
            onPrimaryContainer = dawnText,
            secondary = dawnText,
            onSecondary = if (isDark) dawnForeground else primaryForeground,
            secondaryContainer = systemSelected,
            onSecondaryContainer = dawnText,
            tertiary = dawn,
            onTertiary = dawnForeground,
            tertiaryContainer = systemSelected,
            onTertiaryContainer = dawnText,
            background = background,
            onBackground = foreground,
            surface = background,
            onSurface = foreground,
            surfaceVariant = muted,
            onSurfaceVariant = mutedForeground,
            surfaceTint = Color.Transparent,
            inverseSurface = foreground,
            inverseOnSurface = background,
            inversePrimary = dawn,
            error = destructive,
            onError = destructiveForeground,
            errorContainer = authErrorBackground,
            onErrorContainer = cardForeground,
            outline = mutedForeground,
            outlineVariant = border,
            scrim = Color.Black,
            surfaceBright = popover,
            surfaceDim = surface2,
            surfaceContainer = popover,
            surfaceContainerHigh = popover,
            surfaceContainerHighest = muted,
            surfaceContainerLow = card,
            surfaceContainerLowest = card,
            primaryFixed = systemSelected,
            primaryFixedDim = systemSelected,
            onPrimaryFixed = dawnText,
            onPrimaryFixedVariant = dawnText,
            secondaryFixed = systemSelected,
            secondaryFixedDim = systemSelected,
            onSecondaryFixed = dawnText,
            onSecondaryFixedVariant = dawnText,
            tertiaryFixed = systemSelected,
            tertiaryFixedDim = systemSelected,
            onTertiaryFixed = dawnText,
            onTertiaryFixedVariant = dawnText,
        )
    }
